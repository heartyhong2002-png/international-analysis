        / NULLIF(COUNT(CASE WHEN llm_label IN ('우호적', '중립적', '비판적') THEN 1 END), 0))::numeric, 1) AS critical_pct
FROM cleaned_log
GROUP BY issue, source_type, outlet_bias;


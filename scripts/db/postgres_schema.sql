CREATE OR REPLACE VIEW v_alert_evidence_trace AS
SELECT
    a.id AS alert_event_id,
    a.issue_key,
    a.alert_level,
    a.lifecycle_status AS alert_status,
    a.triggered_at,
    a.decision_rationale,
    sr.run_key,
    sr.scoring_version,
    e.id AS evidence_id,
    e.evidence_role,
    e.source_table,
    e.source_record_key,
    e.source_url,
    e.evidence_quote,
    e.relevance_score,
    e.observed_at,
    rs.signal_family,
    rs.metric_name,
    rs.raw_value,
    rs.normalized_score,
    rs.weight,
    rs.contribution_score,
    rs.confidence_score,
    rs.quality_status
FROM alert_events a
JOIN scoring_runs sr ON sr.id = a.scoring_run_id
LEFT JOIN alert_event_evidence e ON e.alert_event_id = a.id
LEFT JOIN risk_signal_scores rs ON rs.id = e.risk_signal_score_id
WHERE a.issue_key NOT LIKE 'TEST\_%' ESCAPE '\'
  AND sr.scoring_version <> 'test-fixture-v1'
  AND sr.run_key NOT LIKE 'TEST-FIXTURE%';

CREATE OR REPLACE VIEW v_alert_validation_summary AS
SELECT
    v.issue_key,
    COALESCE(a.alert_level, 'NO_ALERT') AS alert_level,
    COUNT(*) AS audit_count,
    SUM(CASE WHEN v.verdict = 'confirmed' THEN 1 ELSE 0 END) AS confirmed_count,
    SUM(CASE WHEN v.verdict = 'false_alarm' THEN 1 ELSE 0 END) AS false_alarm_count,
    SUM(CASE WHEN v.verdict = 'missed_signal' THEN 1 ELSE 0 END) AS missed_signal_count,
    SUM(CASE WHEN v.verdict = 'insufficient_evidence' THEN 1 ELSE 0 END) AS insufficient_evidence_count,
    SUM(CASE WHEN v.reviewer IS NOT NULL THEN 1 ELSE 0 END) AS human_reviewed_count,
    ROUND((100.0 * SUM(CASE WHEN v.alert_event_id IS NOT NULL AND v.verdict = 'confirmed' THEN 1 ELSE 0 END)
        / NULLIF(SUM(CASE WHEN v.alert_event_id IS NOT NULL AND v.verdict IN ('confirmed', 'false_alarm') THEN 1 ELSE 0 END), 0))::numeric, 1) AS alert_precision_pct,
    MAX(v.reviewed_at) AS last_reviewed_at,
    CASE WHEN v.alert_event_id IS NOT NULL THEN 'alert_linked' ELSE 'advisory_history' END AS audit_scope,
    SUM(CASE WHEN v.verdict = 'pending_review' THEN 1 ELSE 0 END) AS pending_review_count,
    SUM(CASE WHEN v.alert_event_id IS NOT NULL AND v.verdict IN ('confirmed', 'false_alarm') THEN 1 ELSE 0 END) AS scored_review_count,
    MAX(CASE WHEN v.alert_event_id IS NOT NULL THEN 1 ELSE 0 END) AS official_kpi_eligible
FROM alert_validation_audit v
LEFT JOIN alert_events a ON a.id = v.alert_event_id
WHERE v.issue_key NOT LIKE 'TEST\_%' ESCAPE '\'
  AND v.audit_type <> 'fixture_review'
GROUP BY
    v.issue_key,
    COALESCE(a.alert_level, 'NO_ALERT'),
    CASE WHEN v.alert_event_id IS NOT NULL THEN 'alert_linked' ELSE 'advisory_history' END;


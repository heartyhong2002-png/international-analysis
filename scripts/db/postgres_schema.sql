CREATE OR REPLACE VIEW v_signal_attention_gap AS
WITH dates AS (
    SELECT DISTINCT safe_rfc2822_date(pub_date) AS dt FROM gov_announcements WHERE pub_date IS NOT NULL
    UNION
    SELECT DISTINCT safe_iso_date(date) AS dt FROM news_data WHERE date IS NOT NULL
    UNION
    SELECT DISTINCT safe_iso_date(published) AS dt FROM reddit_opinion WHERE published IS NOT NULL
    UNION
    SELECT DISTINCT safe_rfc2822_date(published_date) AS dt FROM rss_signal_gap WHERE published_date IS NOT NULL
),
gov_counts AS (
    SELECT safe_rfc2822_date(pub_date) AS dt, COUNT(*) AS gov_count
    FROM gov_announcements
    GROUP BY dt
),
news_counts AS (
    SELECT safe_iso_date(date) AS dt, COUNT(*) AS news_count
    FROM news_data
    GROUP BY dt
),
reddit_counts AS (
    SELECT safe_iso_date(published) AS dt, COUNT(*) AS reddit_count
    FROM reddit_opinion
    GROUP BY dt
),
rss_official AS (
    SELECT safe_rfc2822_date(published_date) AS dt, COUNT(*) AS rss_gov_count
    FROM rss_signal_gap
    WHERE source_type = 'Official'
    GROUP BY dt
),
rss_indep AS (
    SELECT safe_rfc2822_date(published_date) AS dt, COUNT(*) AS rss_indep_count
    FROM rss_signal_gap
    WHERE source_type = 'Independent'
    GROUP BY dt
)
SELECT
    d.dt AS analysis_date,
    (COALESCE(g.gov_count, 0) + COALESCE(ro.rss_gov_count, 0)) AS total_official_signals,
    (COALESCE(n.news_count, 0) + COALESCE(ri.rss_indep_count, 0)) AS total_independent_signals,
    COALESCE(r.reddit_count, 0) AS public_sentiment_signals,
    ABS((COALESCE(g.gov_count, 0) + COALESCE(ro.rss_gov_count, 0)) - (COALESCE(n.news_count, 0) + COALESCE(ri.rss_indep_count, 0))) AS signal_gap_score,
    CASE
        WHEN (COALESCE(n.news_count, 0) + COALESCE(ri.rss_indep_count, 0)) > (COALESCE(g.gov_count, 0) + COALESCE(ro.rss_gov_count, 0)) * 2
         AND (COALESCE(n.news_count, 0) + COALESCE(ri.rss_indep_count, 0)) > 5 THEN 'RED ALERT: High Independent Activity'
        WHEN COALESCE(r.reddit_count, 0) > 5 THEN 'WARNING: High Public Attention'
        ELSE 'NORMAL'
    END AS gap_status
FROM dates d
LEFT JOIN gov_counts g ON d.dt = g.dt
LEFT JOIN news_counts n ON d.dt = n.dt
LEFT JOIN reddit_counts r ON d.dt = r.dt
LEFT JOIN rss_official ro ON d.dt = ro.dt
LEFT JOIN rss_indep ri ON d.dt = ri.dt
WHERE d.dt IS NOT NULL
ORDER BY d.dt DESC;


WITH wiki_daily AS (
    SELECT
        issue,
        date,
        SUM(article_count) AS total_pageviews,
        COUNT(DISTINCT keyword) AS keyword_count
    FROM wikipedia_pageviews
    GROUP BY issue, date
),

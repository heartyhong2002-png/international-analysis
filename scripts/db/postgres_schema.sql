-- Trigger helper for tables that previously used MySQL ON UPDATE CURRENT_TIMESTAMP
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Safe date parsing helpers for views (prevents runtime errors on malformed raw strings)
CREATE OR REPLACE FUNCTION safe_rfc2822_date(raw TEXT)
RETURNS DATE AS $$
BEGIN
    IF raw IS NULL OR btrim(raw) = '' THEN
        RETURN NULL;
    END IF;
    RETURN TO_DATE(SUBSTRING(raw FROM 6 FOR 11), 'DD Mon YYYY');
EXCEPTION WHEN OTHERS THEN
    RETURN NULL;
END;
$$ LANGUAGE plpgsql IMMUTABLE;

CREATE OR REPLACE FUNCTION safe_iso_date(raw TEXT)
RETURNS DATE AS $$
BEGIN
    IF raw IS NULL OR btrim(raw) = '' THEN
        RETURN NULL;
    END IF;
    RETURN SUBSTRING(btrim(raw) FROM 1 FOR 10)::DATE;
EXCEPTION WHEN OTHERS THEN
    RETURN NULL;
END;
$$ LANGUAGE plpgsql IMMUTABLE;


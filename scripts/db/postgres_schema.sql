    SELECT
        m.issue,
        g.collected_date AS date,
        COUNT(DISTINCT g.id) AS gov_announcement_count,
        COUNT(DISTINCT CASE WHEN g.source_type = 'official_statement' THEN g.id END) AS official_stmt_count,

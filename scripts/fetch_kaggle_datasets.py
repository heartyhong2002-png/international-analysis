def validate_and_report_manifest(df: pd.DataFrame) -> dict:
    """매니페스트 데이터프레임의 정합성을 검증하고 주요 통계를 반환"""
    expected_cols = [
        "date_gregorian", "date_jalali", "weekday_fa",
        "issue_no", "issue_id", "pages_total", "pages_downloaded", "status"
    ]
    missing_cols = [c for c in expected_cols if c not in df.columns]
    if missing_cols:
        raise ValueError(f"필수 컬럼 누락: {missing_cols}")

    total_issues = len(df)
    min_date = df["date_gregorian"].min()
    max_date = df["date_gregorian"].max()

    status_counts = df["status"].value_counts().to_dict()
    page_dist = df["pages_total"].value_counts().to_dict()

    partial_df = df[df["status"] != "OK"]

    print("\n" + "=" * 55)
    print("📊 [Kayhan 아카이브 매니페스트 무결성 점검 결과]")
    print(f" • 총 수집 호수: {total_issues}건")
    print(f" • 수집 기간: {min_date} ~ {max_date}")
    print(f" • 다운로드 상태: {status_counts}")
    print(f" • 지면 수 분포: {page_dist}")

    if not partial_df.empty:
        print(f"\n ⚠️ 재수집/부분 수집(PARTIAL) 대상 {len(partial_df)}건 발견:")
        for _, row in partial_df.iterrows():
            print(f"    - [{row['date_gregorian']}] {row['issue_no']}호 (ID: {row['issue_id']}): "
                  f"{row['pages_downloaded']}/{row['pages_total']}면 ({row['status']})")
    else:
        print(" ✅ 모든 호수가 정상(OK) 다운로드 상태입니다.")
    print("=" * 55 + "\n")

    return {
        "total": total_issues,
        "min_date": min_date,
        "max_date": max_date,
        "partial_count": len(partial_df)
    }


